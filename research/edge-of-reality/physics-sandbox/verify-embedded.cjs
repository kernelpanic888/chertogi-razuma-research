assert.ok(reader.indexOf('<section id="s4b">')<reader.indexOf('<section id="s5">'));
assert.equal((reader.match(/id="er01-physics-sandbox"/g)||[]).length,1);
assert.equal((reader.match(/id="physics-sandbox-entry"/g)||[]).length,1);
